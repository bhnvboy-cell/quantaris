-- Quantaris - QFD (Quality Function Deployment) (MySQL)
CREATE TABLE IF NOT EXISTS QFDModels (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    TenantId INT NOT NULL,
    ProjectId INT NOT NULL,
    ModelName VARCHAR(200) NOT NULL,
    CreatedOn DATETIME DEFAULT CURRENT_TIMESTAMP,
    CreatedByUserId INT,
    CONSTRAINT fk_qfd_tenant FOREIGN KEY (TenantId) REFERENCES Tenants(Id),
    CONSTRAINT fk_qfd_project FOREIGN KEY (ProjectId) REFERENCES QuantarisProjects(Id),
    CONSTRAINT fk_qfd_user FOREIGN KEY (CreatedByUserId) REFERENCES Users(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS QFDRequirements (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    ModelId INT NOT NULL,
    ReqType VARCHAR(20) NOT NULL,
    ReqIndex INT NOT NULL,
    ReqName VARCHAR(200) NOT NULL,
    Weight DOUBLE DEFAULT 1.0,
    CONSTRAINT fk_qfdr_model FOREIGN KEY (ModelId) REFERENCES QFDModels(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS QFDMatrix (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    ModelId INT NOT NULL,
    CustomerReqId INT NOT NULL,
    TechnicalReqId INT NOT NULL,
    Rating INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_qfdm_model FOREIGN KEY (ModelId) REFERENCES QFDModels(Id) ON DELETE CASCADE,
    CONSTRAINT fk_qfdm_cust FOREIGN KEY (CustomerReqId) REFERENCES QFDRequirements(Id) ON DELETE CASCADE,
    CONSTRAINT fk_qfdm_tech FOREIGN KEY (TechnicalReqId) REFERENCES QFDRequirements(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS QFDCorrelations (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    ModelId INT NOT NULL,
    TechReq1Id INT NOT NULL,
    TechReq2Id INT NOT NULL,
    Correlation VARCHAR(10) NOT NULL,
    CONSTRAINT fk_qfdc_model FOREIGN KEY (ModelId) REFERENCES QFDModels(Id) ON DELETE CASCADE,
    CONSTRAINT fk_qfdc_req1 FOREIGN KEY (TechReq1Id) REFERENCES QFDRequirements(Id) ON DELETE CASCADE,
    CONSTRAINT fk_qfdc_req2 FOREIGN KEY (TechReq2Id) REFERENCES QFDRequirements(Id) ON DELETE CASCADE
) ENGINE=InnoDB;
